-- Push notification device tokens.
-- Run this once in the Supabase SQL editor before deploying the push endpoints.
-- The server uses SUPABASE_SERVICE_ROLE_KEY to read/write this table, so no
-- public RLS policies are granted: tokens must never be readable by browsers.

create table if not exists public.device_tokens (
  id bigint generated by default as identity primary key,
  token text not null unique,
  platform text not null default 'android',
  role text not null default 'customer',
  user_id text not null default '',
  phone text not null default '',
  session_id text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists device_tokens_role_idx on public.device_tokens (role);
create index if not exists device_tokens_phone_idx on public.device_tokens (phone);
create index if not exists device_tokens_user_idx on public.device_tokens (user_id);
create index if not exists device_tokens_session_idx on public.device_tokens (session_id);

alter table public.device_tokens enable row level security;

-- Intentionally no anon/authenticated policies. The Express server uses the
-- service role key, which bypasses RLS.
